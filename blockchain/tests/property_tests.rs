use proptest::prelude::*;
use rand::rngs::OsRng;
use ed25519_dalek::SigningKey;
use tokio::runtime::Runtime;

use vera_blockchain::account::{Account, address_from_pubkey};
use vera_blockchain::csmt::CSMT;
use vera_blockchain::state_transition::{BURN_ADDRESS, STABILITY_POOL_ADDRESS, StateTransitionEngine};
use vera_blockchain::transaction::Transaction;

proptest! {
    /// Property 1 — Law of Conservation of $VERA (Conservation Law)
    /// For ANY valid transaction with random inputs, the total sum of $VERA
    /// in the system before the transaction is strictly identical to total sum after transaction.
    /// sum(Alice + Bob + Proposer + StabilityPool + BurnAddress) == initial_balance
    #[test]
    fn prop_conservation_of_vera(
        initial_balance in 1_000_000u128..10_000_000_000u128,
        transfer_amount in 0u128..500_000_000u128,
        gas_limit in 21_000u64..100_000u64,
        gas_price in 1u64..100u64,
    ) {
        let mut csprng = OsRng;
        let alice_key = SigningKey::generate(&mut csprng);
        let alice_addr = address_from_pubkey(&alice_key.verifying_key().to_bytes());

        let bob_key = SigningKey::generate(&mut csprng);
        let bob_addr = address_from_pubkey(&bob_key.verifying_key().to_bytes());

        let prop_key = SigningKey::generate(&mut csprng);
        let prop_addr = address_from_pubkey(&prop_key.verifying_key().to_bytes());

        // Ensure all addresses are distinct and none collide with protocol addresses
        prop_assume!(alice_addr != bob_addr);
        prop_assume!(alice_addr != prop_addr);
        prop_assume!(bob_addr != prop_addr);
        prop_assume!(alice_addr != BURN_ADDRESS && alice_addr != STABILITY_POOL_ADDRESS);
        prop_assume!(bob_addr != BURN_ADDRESS && bob_addr != STABILITY_POOL_ADDRESS);
        prop_assume!(prop_addr != BURN_ADDRESS && prop_addr != STABILITY_POOL_ADDRESS);

        let max_gas_cost = (gas_limit as u128).saturating_mul(gas_price as u128);
        let total_required = transfer_amount.saturating_add(max_gas_cost);
        prop_assume!(initial_balance >= total_required);

        let mut csmt = CSMT::new();
        csmt.insert(alice_addr, Account::new(initial_balance).to_bytes());

        let tx = Transaction::new(
            "vera-testnet-1",
            &alice_key,
            0,
            Some(bob_addr),
            transfer_amount,
            gas_limit,
            gas_price,
            vec![],
        );

        let rt = Runtime::new().unwrap();
        let receipt = rt.block_on(StateTransitionEngine::execute_transaction(&mut csmt, &tx, prop_addr));
        prop_assert!(receipt.is_ok(), "Transaction execution failed: {:?}", receipt.err());

        let mut total_after: u128 = 0;
        for (_k, v) in csmt.to_key_values() {
            let acc = Account::from_bytes(&v).unwrap();
            total_after = total_after.checked_add(acc.balance).expect("Overflow summing balances");
        }

        prop_assert_eq!(
            total_after,
            initial_balance,
            "Violation of Conservation Law: total before ({}) != total after ({})",
            initial_balance,
            total_after
        );
    }

    /// Property 2 — Idempotence and Signature Validity
    /// For ANY key and random transaction parameters,
    /// the signature generated by Transaction::new is ALWAYS cryptographically valid.
    #[test]
    fn prop_signature_always_valid_after_creation(
        nonce in 0u64..1000u64,
        amount in 0u128..1_000_000u128,
        gas_limit in 21_000u64..50_000u64,
        gas_price in 1u64..10u64,
    ) {
        let mut csprng = OsRng;
        let key = SigningKey::generate(&mut csprng);
        let recipient_key = SigningKey::generate(&mut csprng);
        let recipient_addr = address_from_pubkey(&recipient_key.verifying_key().to_bytes());

        let tx = Transaction::new(
            "vera-testnet-1",
            &key,
            nonce,
            Some(recipient_addr),
            amount,
            gas_limit,
            gas_price,
            vec![],
        );

        prop_assert!(
            tx.verify_signature().is_ok(),
            "Generated signature failed Ed25519 validation"
        );
    }

    /// Property 3 — Strictly Monotonic Nonce
    /// After N transactions executed sequentially from the same account,
    /// the account's final nonce MUST be strictly N.
    #[test]
    fn prop_nonce_strictly_monotonic(n in 1usize..20usize) {
        let mut csprng = OsRng;
        let alice_key = SigningKey::generate(&mut csprng);
        let alice_addr = address_from_pubkey(&alice_key.verifying_key().to_bytes());
        let bob_key = SigningKey::generate(&mut csprng);
        let bob_addr = address_from_pubkey(&bob_key.verifying_key().to_bytes());
        let prop_key = SigningKey::generate(&mut csprng);
        let prop_addr = address_from_pubkey(&prop_key.verifying_key().to_bytes());

        let mut csmt = CSMT::new();
        let initial_balance = 100_000_000_000u128;
        csmt.insert(alice_addr, Account::new(initial_balance).to_bytes());

        let rt = Runtime::new().unwrap();

        for i in 0..n {
            let tx = Transaction::new(
                "vera-testnet-1",
                &alice_key,
                i as u64,
                Some(bob_addr),
                1_000,
                25_000,
                1,
                vec![],
            );
            let res = rt.block_on(StateTransitionEngine::execute_transaction(&mut csmt, &tx, prop_addr));
            prop_assert!(res.is_ok(), "Tx {} with nonce {} failed: {:?}", i, i, res.err());
        }

        let alice_bytes = csmt.get(&alice_addr).expect("Alice account must exist");
        let alice_acc = Account::from_bytes(alice_bytes).unwrap();
        prop_assert_eq!(
            alice_acc.nonce,
            n as u64,
            "Incorrect final nonce: expected {}, found {}",
            n,
            alice_acc.nonce
        );
    }

    /// Property 4 — Safe Self-Transfer
    /// Sending tokens to oneself fully preserves principal balance,
    /// deducting strictly the calculated gas fee.
    #[test]
    fn prop_self_transfer_preserves_balance(
        balance in 1_000_000u128..1_000_000_000u128,
        amount in 0u128..500_000_000u128,
        gas_price in 1u64..50u64,
    ) {
        let gas_limit = 25_000u64;
        let max_gas = (gas_limit as u128) * (gas_price as u128);
        prop_assume!(balance >= amount.saturating_add(max_gas));

        let mut csprng = OsRng;
        let alice_key = SigningKey::generate(&mut csprng);
        let alice_addr = address_from_pubkey(&alice_key.verifying_key().to_bytes());
        let prop_key = SigningKey::generate(&mut csprng);
        let prop_addr = address_from_pubkey(&prop_key.verifying_key().to_bytes());
        prop_assume!(prop_addr != alice_addr);

        let mut csmt = CSMT::new();
        csmt.insert(alice_addr, Account::new(balance).to_bytes());

        let tx = Transaction::new(
            "vera-testnet-1",
            &alice_key,
            0,
            Some(alice_addr), // Self-transfer
            amount,
            gas_limit,
            gas_price,
            vec![],
        );

        let rt = Runtime::new().unwrap();
        let receipt = rt.block_on(StateTransitionEngine::execute_transaction(&mut csmt, &tx, prop_addr))
            .expect("Self-transfer must succeed");

        let alice_bytes = csmt.get(&alice_addr).expect("Alice must exist");
        let alice_acc = Account::from_bytes(alice_bytes).unwrap();

        let gas_cost = (receipt.gas_used as u128) * (gas_price as u128);
        let expected_balance = balance - gas_cost;
        prop_assert_eq!(
            alice_acc.balance,
            expected_balance,
            "Self-transfer corrupted balance! Expected: {}, Found: {}",
            expected_balance,
            alice_acc.balance
        );
    }

    /// Property 5 — Deterministic Insufficient Balance Rejection
    /// If amount + max_gas > balance, the transaction must be rejected
    /// and no $VERA can be created or altered in state.
    #[test]
    fn prop_insufficient_balance_never_creates_vera(
        balance in 0u128..100_000u128,
        amount in 100_001u128..1_000_000u128,
        gas_price in 1u64..10u64,
    ) {
        let gas_limit = 21_000u64;
        let mut csprng = OsRng;
        let alice_key = SigningKey::generate(&mut csprng);
        let alice_addr = address_from_pubkey(&alice_key.verifying_key().to_bytes());
        let bob_key = SigningKey::generate(&mut csprng);
        let bob_addr = address_from_pubkey(&bob_key.verifying_key().to_bytes());
        let prop_key = SigningKey::generate(&mut csprng);
        let prop_addr = address_from_pubkey(&prop_key.verifying_key().to_bytes());

        let mut csmt = CSMT::new();
        csmt.insert(alice_addr, Account::new(balance).to_bytes());

        let tx = Transaction::new(
            "vera-testnet-1",
            &alice_key,
            0,
            Some(bob_addr),
            amount,
            gas_limit,
            gas_price,
            vec![],
        );

        let rt = Runtime::new().unwrap();
        let result = rt.block_on(StateTransitionEngine::execute_transaction(&mut csmt, &tx, prop_addr));

        // Must fail with insufficient balance error
        prop_assert!(
            result.is_err(),
            "Transaction with insufficient balance was improperly executed"
        );

        // Alice state must remain identical
        let alice_bytes = csmt.get(&alice_addr).unwrap();
        let alice_acc = Account::from_bytes(alice_bytes).unwrap();
        prop_assert_eq!(
            alice_acc.balance,
            balance,
            "Alice balance altered in rejected transaction"
        );

        // No coins created in CSMT
        let mut total_supply: u128 = 0;
        for (_k, v) in csmt.to_key_values() {
            let acc = Account::from_bytes(&v).unwrap();
            total_supply = total_supply.checked_add(acc.balance).unwrap();
        }
        prop_assert_eq!(
            total_supply,
            balance,
            "Total supply corrupted in rejected transaction"
        );
    }
}
